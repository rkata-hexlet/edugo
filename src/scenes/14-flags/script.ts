/** Время кадра без голоса: база + чтение текста в кадре. */
export function holdFor(caption: string, w: World): number {
  const text = [caption, w.plate ?? "", w.stamp ?? "", w.db ?? "", w.dutySay ?? "", w.guestSay ?? "", w.podSay?.text ?? ""].join("");
  return Math.round((1.5 + 0.035 * text.length) * 10) / 10;
}

class Shots extends Director<Focus, World> {
  private replaying = false;

  constructor() {
    super(world);
  }

  override scene(act: string, w?: World, o?: { replay?: boolean }): void {
    super.scene(act, w, o);
    this.replaying = act === ACT.summary;
  }

  protected hold(caption: string, w: World): number {
    return holdFor(caption, w);
  }

  protected override clear(w: World): void {
    w.visits = [];
    w.guestSay = null;
    w.dutySay = null;
    w.podSay = null;
    w.code = [];
    w.codeMark = null;
    for (const p of Object.values(w.pods)) p.hanging = false;
  }

  protected override finish(w: World): void {
    w.replay = this.replaying;
  }
}

/** Сервис бронирования; подготовка до кадра — без событий. */
function hotel(mode: Mode = "direct", prep: (w: World) => void = () => {}): World {
  const w = world();
  w.mode = mode;
  prep(w);
  w.visits = [];
  w.events = [];
  for (const p of Object.values(w.pods)) p.fresh = false;
  return w;
}

/** Флаг включён на `percent` процентов. */
